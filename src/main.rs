use zort::matrix::Matrix;

fn main() {
    let mut a: Matrix<f64> = Matrix::from([
        [2.111, 2.431, 5.12],
        [7.535, 12.654, 24.671],
        [1.5, 5.4, 224.1],
        [7.535, -12.654, 234.671],
    ]);

    let b: Matrix<f64> = Matrix::from([
        [2.111, 2.431, 5.12],
        [7.535, 12.654, 24.671],
        [1.5, 5.4, 224.1],
        [7.535, -12.654, 234.671],
    ]);
    println!("{:.3}", a);
    a.add(&b);
    println!("{:.3?}", a);
}
